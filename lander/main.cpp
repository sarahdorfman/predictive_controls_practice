#include "DARE.h"
#include "kalman.h"
#include <iostream>
#include <stdexcept>
#include <fstream>
#include <random>
#include <eigen3/Eigen/Dense>
#include <vector>
#include <algorithm>

#define P_SIGMA_H  0.01
#define P_SIGMA_G 0.1

#define M_SIGMA 1.


using namespace std;

double g,height,v,t;

  double dt;


void fall_init(double x0, double gravity)
{
	  g=gravity; 
        height= x0;
        v=0;
}
// falling with noise injected and control input u.
double falling(double noise_p,double noise_g,double u)
{
  height=height+dt*v + dt*noise_p;
  v=v-dt*(g+noise_g)+dt*u;
  return(height);
}

void setup(void)
{
  int n = 3; // Number of states
  int m = 1; // Number of measurements

  // SOME NOISE
  std::default_random_engine generator;
  std::normal_distribution<double> p_noise_h(0.0,P_SIGMA_H);
  std::normal_distribution<double> p_noise_g(0.0,P_SIGMA_G);
  std::normal_distribution<double> m_noise(0.0,M_SIGMA);

  dt = 1.0/30; // Time step



  int horizon=10;

  ofstream myfile;
  myfile.open ("OUT");

  // SISO
  Eigen::MatrixXd A(n, n); 
  Eigen::MatrixXd B(n, m); 
  Eigen::MatrixXd C(m, n); // Output matrix
  Eigen::MatrixXd Q(n, n); 
  Eigen::MatrixXd R(m, m); 
  Eigen::MatrixXd P(n, n); // Estimate error covariance



  A << 1.,dt,0,  0,1,-dt,  0,0,1;
  B << 0.,dt,0.;
  C << 1,0,0;
  Q <<P_SIGMA_H*P_SIGMA_H  ,0.,0, 0,0,0, 0,0,P_SIGMA_G*P_SIGMA_G ;
  R << M_SIGMA*M_SIGMA;

  P <<  1,0,0,  0,1,0, 0,0,1;

  std::cout << "A: \n" << A << std::endl;
  std::cout << "C: \n" << C << std::endl;
  std::cout << "Q: \n" << Q << std::endl;
  std::cout << "R: \n" << R << std::endl;
  std::cout << "P: \n" << P << std::endl;

  KalmanFilter kf(dt,A,B, C, Q, R, P);


  Eigen::VectorXd x0(n);
  // The third is initial guess of gravity
  x0 << 110,0,0;
  //x0 << 100,0,2; ///  WOrks even with wrong sign
  kf.init(dt,x0);


  fall_init(100,5.5); // Physical conditions

  FILE* log;
  log=fopen("DATA","w");

  
  double t = 0;
  int num=100;
  Eigen::VectorXd y(m);

  y << falling(0.,0.,0.);

  Q.setIdentity();
  R<<1;


  // Construct the  SYSTEM
  DARE contr(A, B, Q,R, horizon );

  contr.init();

  contr.print();

 Eigen::IOFormat fmt(5, 0, ", ", " ", "", "", "", "");

Eigen::VectorXd x_est(n);
Eigen::VectorXd u(m);

int i = 0;


  fprintf(log,"%f\t %f\t%f\t%f\t%f \n",t, y(0),  kf.state()[0],kf.state()[1],kf.state()[2]);

  while(y[0]>0.){

    // chat gpt helped with bug find, this is the last controller gain after reaching the horizon end
    int gain_index = std::min(i, horizon - 1);

    // Get current estimated state
    x_est = kf.state();

    // calculate the control input
    u= -1* contr.getK(gain_index) *x_est;
    //update time
    t += dt;

    // fall with input
    y << falling(p_noise_h(generator),p_noise_g(generator),u(0));

    //sensor noise measurement
    y(0)+=m_noise(generator);

    // update kalman filter with control input
    kf.update(y,u(0));

    //printf("%f\t %f\t%f\t%f\t%f \n",t, y(0),  kf.state()[0],kf.state()[1],kf.state()[2]);
    fprintf(log,"%f\t %f\t%f\t%f\t%f \n",t, y(0),  kf.state()[0],kf.state()[1],kf.state()[2]);
  
    // generated by chatgpt to modify the output file
    myfile << t << "\t"
       << y(0) << "\t"
       << kf.state()[0] << "\t"
       << kf.state()[1] << "\t"
       << kf.state()[2] << "\t"
       << g << std::endl;

    i++;

  }

   myfile.close();
}

int main(void)
{
	setup();
	return(0);
}
